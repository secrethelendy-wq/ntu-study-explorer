test('全部紀錄、照片與同棟群集可實際操作',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await expect(page.getByTestId('results-count')).toContainText('15')
  await expect(page.locator('.space-card')).toHaveCount(15)
  await page.getByRole('button',{name:'列表模式',exact:true}).click()
  await expect(page.locator('.map-column')).toBeHidden()
  const photos=page.locator('.card-photo')
  for(let i=0;i<await photos.count();i++){
    await photos.nth(i).scrollIntoViewIfNeeded()
    await expect.poll(()=>photos.nth(i).evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBe(true)
  }
  await page.getByRole('button',{name:'地圖模式',exact:true}).click()
  const group=page.locator('.leaflet-marker-icon[title="社會科學院大樓，2 個自習空間"]')
  await group.click()
  await expect(page.locator('.leaflet-popup')).toBeVisible()
  await expect(page.locator('.popup-space')).toHaveCount(2)
  await expect(page.locator('.popup-space').last()).toContainText('307 席')
  await page.locator('.popup-detail').last().click()
  await expect(page).toHaveURL(/#\/space\/s14/)
  await expect(page.locator('h1')).toContainText('辜振甫')
  expect(errors).toEqual([])
})

