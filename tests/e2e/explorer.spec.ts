test('直接開檔保留資料，但不向 OSM 發送缺少來源的請求',async({page})=>{
  await page.waitForLoadState('networkidle')
  const requests:string[]=[]
  page.on('request',r=>{if(r.url().startsWith('https://tile.openstreetmap.org/'))requests.push(r.url())})
  await page.goto(pathToFileURL(path.resolve('dist/preview.html')).href)
  await expect(page.locator('.space-card')).toHaveCount(15)
  await expect(page.locator('.leaflet-marker-icon')).toHaveCount(13)
  await expect(page.locator('.map-error')).toContainText('啟動網站.cmd')
  await expect.poll(()=>page.locator('.card-photo').first().evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBe(true)
  await expect(page.getByRole('link',{name:'開啟 HTTP 預覽 ↗'})).toHaveAttribute('href','http://127.0.0.1:4173/')
  await page.waitForLoadState('networkidle')
  expect(requests).toEqual([])
})
