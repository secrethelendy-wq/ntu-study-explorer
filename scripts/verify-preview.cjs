const { chromium }=require('playwright')
const assert=require('node:assert/strict')
const path=require('node:path')
const {pathToFileURL}=require('node:url')
;(async()=>{
  const browser=await chromium.launch({channel:'chrome'})
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  const tileRequests=[];page.on('request',r=>{if(r.url().startsWith('https://tile.openstreetmap.org/'))tileRequests.push(r.url())});
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  const url=pathToFileURL(path.resolve('dist/preview.html')).href
  await page.goto(url,{waitUntil:'domcontentloaded'})
  await page.waitForSelector('.leaflet-marker-icon')
  assert.equal(await page.locator('.space-card').count(),15)
  assert.equal(await page.locator('.leaflet-marker-icon').count(),13)
  await page.getByRole('button',{name:'安靜讀書',exact:true}).click()
  await page.getByRole('button',{name:'帶電腦去',exact:true}).click()
  assert.equal(await page.locator('.space-card').count(),2)
  await page.locator('.compare-button').first().click()
  await page.locator('.compare-button').last().click()
  await page.getByRole('button',{name:'開始比較'}).click()
  assert.ok(await page.getByRole('dialog').isVisible())
  await page.keyboard.press('Escape')
  await page.goto(url+'#/space/s07')
  await page.waitForSelector('.gallery-thumbnails')
  for(let i=0;i<4;i++){
    await page.getByRole('button',{name:`查看照片 ${i+1}`,exact:true}).click()
    await page.waitForFunction(()=>{const img=document.querySelector('.gallery-main img');return img&&img.complete&&img.naturalWidth>0})
  }
  await page.locator('.raw-metadata summary').click()
  assert.equal(await page.locator('.raw-metadata dt').count(),13)
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
  await page.goto(url+'#/')
  await page.waitForSelector('.leaflet-marker-icon')
  await page.getByRole('button',{name:/^篩選/}).click()
  assert.ok(await page.locator('.filters-panel').isVisible())
  assert.deepEqual(errors,[])
  assert.deepEqual(tileRequests,[])
  assert.ok(await page.locator('.map-error').isVisible())
  console.log(JSON.stringify({previewProtocol:'file:',publicTileRequests:tileRequests.length,mode:'metadata-only local preview',desktopAndMobile:true,searchAndFilters:true,comparison:true,originalPhotoGallery:4,rawMetadataFields:13,errors}))
  await browser.close()
})().catch(e=>{console.error(e);process.exit(1)})
